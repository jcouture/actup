package lock

import (
	"bytes"
	"fmt"
	"reflect"
	"sort"
	"strconv"

	"github.com/github/actions-lockfile/go/pkg/lockfile"
)

func Parse(contents []byte) (lockfile.File, error) {
	f, err := lockfile.Parse(contents)
	if err != nil {
		return f, fmt.Errorf("parse %s: %w", lockfile.Path, err)
	}
	return f, nil
}

func Encode(f lockfile.File) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("# This file is machine-generated by actup.\n# Do not edit by hand.\n")
	b.WriteString("version: " + strconv.Quote(lockfile.Version) + "\nworkflows:\n")
	paths := make([]string, 0, len(f.Workflows))
	for path := range f.Workflows {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		deps := append([]string(nil), f.Workflows[path]...)
		sort.Strings(deps)
		b.WriteString("  " + strconv.Quote(path) + ":")
		if len(deps) == 0 {
			b.WriteString(" []\n")
		} else {
			b.WriteByte('\n')
			for _, dep := range deps {
				b.WriteString("    - " + strconv.Quote(dep) + "\n")
			}
		}
	}
	b.WriteString("dependencies:\n")
	keys := make([]string, 0, len(f.Dependencies))
	for key := range f.Dependencies {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		dep := f.Dependencies[key]
		b.WriteString("  " + strconv.Quote(key) + ":\n")
		b.WriteString("    ref: " + strconv.Quote(dep.Ref) + "\n")
		b.WriteString("    commit: " + strconv.Quote(dep.Commit) + "\n")
		b.WriteString("    owner_id: " + strconv.FormatInt(dep.OwnerID, 10) + "\n")
		b.WriteString("    repo_id: " + strconv.FormatInt(dep.RepoID, 10) + "\n")
		if len(dep.Uses) > 0 {
			uses := append([]string(nil), dep.Uses...)
			sort.Strings(uses)
			b.WriteString("    uses:\n")
			for _, u := range uses {
				b.WriteString("      - " + strconv.Quote(u) + "\n")
			}
		}
	}
	if _, err := lockfile.Parse(b.Bytes()); err != nil {
		return nil, fmt.Errorf("generated lockfile invalid: %w", err)
	}
	return b.Bytes(), nil
}
func Equal(a, b lockfile.File) bool {
	if len(a.Workflows) != len(b.Workflows) || len(a.Dependencies) != len(b.Dependencies) {
		return false
	}
	for key, x := range a.Workflows {
		y, ok := b.Workflows[key]
		if !ok || !sameStrings(x, y) {
			return false
		}
	}
	for key, x := range a.Dependencies {
		y, ok := b.Dependencies[key]
		if !ok {
			return false
		}
		if x.Hostname != y.Hostname || x.Ref != y.Ref || x.Commit != y.Commit || x.OwnerID != y.OwnerID || x.RepoID != y.RepoID || !sameStrings(x.Uses, y.Uses) {
			return false
		}
	}
	return true
}
func sameStrings(a, b []string) bool {
	a = append([]string(nil), a...)
	b = append([]string(nil), b...)
	sort.Strings(a)
	sort.Strings(b)
	return reflect.DeepEqual(a, b)
}
